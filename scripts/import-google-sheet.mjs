#!/usr/bin/env node
// Converts the old Google Sheet tabs (downloaded as CSV) into SQL for the D1 giveaway database.
//
//   node scripts/import-google-sheet.mjs Customers.csv Entries.csv [Events.csv] > sheet-import.local.sql
//   npx wrangler d1 execute thistle-giveaway --remote --file=sheet-import.local.sql
//
// Every insert is "ON CONFLICT DO NOTHING", so running it twice never duplicates anyone.
import fs from 'node:fs';

const SCHEMA = {
  Events: ['event_id', 'name', 'opens_at', 'closes_at', 'draw_at', 'eligibility', 'rules', 'status'],
  Customers: ['customer_id', 'created_at', 'name', 'email', 'phone', 'city', 'zip', 'email_opt_in_at', 'sms_opt_in_at', 'email_suppressed', 'sms_suppressed'],
  Entries: ['entry_id', 'event_id', 'event_name', 'customer_id', 'entered_at', 'pet_name', 'breed', 'size', 'other_pets', 'email_opt_in', 'sms_opt_in', 'consent_version', 'email_consent_text', 'sms_consent_text', 'rules_accepted', 'rules_text']
};

export function parseCsv(text) {
  const rows = []; let row = []; let field = ''; let quoted = false;
  text = text.replace(/^﻿/, '');
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(field); field = ''; }
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows.filter(r => r.some(value => value !== ''));
}

function table(file, name) {
  const [header, ...rows] = parseCsv(fs.readFileSync(file, 'utf8'));
  if (!header || header.join(',') !== SCHEMA[name].join(',')) throw new Error(`${file} doesn't look like the ${name} tab. Expected columns: ${SCHEMA[name].join(', ')}`);
  return rows.map(r => Object.fromEntries(header.map((key, i) => [key, r[i] ?? ''])));
}

const sql = value => value === null ? 'NULL' : typeof value === 'number' ? String(value) : "'" + String(value).replace(/'/g, "''") + "'";
const text = value => String(value).replace(/^'/, '').trim();
const optional = value => text(value) || null;
const flag = value => /^(true|yes|1)$/i.test(text(value)) ? 1 : 0;

export function toSql({customers, entries, events = []}) {
  const out = ['-- Generated by scripts/import-google-sheet.mjs'];
  for (const e of events) {
    out.push(`INSERT INTO events (id, name, opens_at, closes_at, draw_at, eligibility, rules, status) VALUES (${[e.event_id, e.name, e.opens_at, e.closes_at, e.draw_at, e.eligibility, e.rules, text(e.status).toLowerCase() || 'paused'].map(v => sql(text(v))).join(', ')}) ON CONFLICT DO NOTHING;`);
  }
  for (const c of customers) {
    out.push(`INSERT INTO customers (id, created_at, name, email, phone, city, zip, email_opt_in_at, sms_opt_in_at, email_suppressed, sms_suppressed) VALUES (${[
      sql(text(c.customer_id)), sql(text(c.created_at)), sql(text(c.name)), sql(text(c.email).toLowerCase()), sql(text(c.phone)), sql(text(c.city)), sql(text(c.zip)),
      sql(optional(c.email_opt_in_at)), sql(optional(c.sms_opt_in_at)), flag(c.email_suppressed), flag(c.sms_suppressed)
    ].join(', ')}) ON CONFLICT DO NOTHING;`);
  }
  for (const e of entries) {
    out.push(`INSERT INTO entries (id, event_id, customer_id, entered_at, pet_name, breed, size, other_pets, email_opt_in, sms_opt_in, consent_version, email_consent_text, sms_consent_text, rules_accepted, rules_text) VALUES (${[
      sql(text(e.entry_id)), sql(text(e.event_id)), sql(text(e.customer_id)), sql(text(e.entered_at)), sql(text(e.pet_name)), sql(text(e.breed)), sql(text(e.size)), sql(text(e.other_pets)),
      flag(e.email_opt_in), flag(e.sms_opt_in), sql(text(e.consent_version)), sql(text(e.email_consent_text)), sql(text(e.sms_consent_text)), flag(e.rules_accepted), sql(String(e.rules_text))
    ].join(', ')}) ON CONFLICT DO NOTHING;`);
  }
  return out.join('\n') + '\n';
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [customersFile, entriesFile, eventsFile] = process.argv.slice(2);
  if (!customersFile || !entriesFile) {
    console.error('Usage: node scripts/import-google-sheet.mjs Customers.csv Entries.csv [Events.csv] > sheet-import.local.sql');
    process.exit(1);
  }
  const data = {customers: table(customersFile, 'Customers'), entries: table(entriesFile, 'Entries'), events: eventsFile ? table(eventsFile, 'Events') : []};
  process.stdout.write(toSql(data));
  console.error(`Prepared ${data.customers.length} customers, ${data.entries.length} entries and ${data.events.length} events.`);
}
